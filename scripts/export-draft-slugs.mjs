import fs from 'node:fs/promises';
import path from 'node:path';
import { REPOS_DIR, readAllRepoRecords } from './lib/repo-frontmatter.mjs';

const outDir = path.resolve('functions/_generated');
const outFile = path.join(outDir, 'draft-slugs.js');

const slugs = (await readAllRepoRecords(REPOS_DIR))
  .filter((record) => record.draft)
  .map((record) => record.slug)
  .sort();

await fs.mkdir(outDir, { recursive: true });
await fs.writeFile(
  outFile,
  `// Generated by scripts/export-draft-slugs.mjs. Do not edit by hand.\n` +
    `export const draftSlugs = new Set(${JSON.stringify(slugs, null, 2)});\n`,
);

console.log(`Exported ${slugs.length} draft slugs to ${path.relative(process.cwd(), outFile)}`);
